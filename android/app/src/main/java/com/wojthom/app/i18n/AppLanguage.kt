package com.wojthom.app.i18n

enum class AppLanguage(val code: String, val nativeLabel: String) {
    POLISH("pl", "Polski"),
    ENGLISH("en", "English"),
    NORWEGIAN("nb", "Norsk");

    companion object {
        fun fromCode(code: String?): AppLanguage = when (code) {
            "no", "nb" -> NORWEGIAN
            "en" -> ENGLISH
            else -> POLISH
        }
    }
}

